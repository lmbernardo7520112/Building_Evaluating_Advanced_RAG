@dataclass(frozen=True, slots=True)
class Checkpoint:
    """A resumable checkpoint tied to specific config and corpus.

    Invariants:
    - run_id must be valid
    - corpus_fingerprint ties checkpoint to specific corpus version
    - config_fingerprint ties checkpoint to specific configuration
    """

    run_id: RunId
    corpus_fingerprint: IntegrityDigest
    config_fingerprint: IntegrityDigest
    completed_query_ids: frozenset[str] = field(default_factory=frozenset)
    question_states: dict[str, QuestionState] = field(default_factory=dict)

    def __post_init__(self) -> None:
        # Validate that question_states is not mutable through the frozen dataclass
        # by ensuring it's a proper dict (will be shallow-frozen by frozen=True)
        pass

    def is_compatible(
        self,
        corpus_fp: IntegrityDigest,
        config_fp: IntegrityDigest,
    ) -> bool:
        """Check if checkpoint matches current run configuration."""
        return (
            self.corpus_fingerprint == corpus_fp
            and self.config_fingerprint == config_fp
        )


